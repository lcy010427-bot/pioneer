const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const time=require('../web/timeline.js');
const base=process.env.PIONEER_URL||'http://127.0.0.1:8765';
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});const errors=[];
 page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 const initial=await(await page.request.get(base+'/api/research')).json();
 const anchor=initial.chemicals.map(time.coverage).filter(Boolean).map(c=>c.end).sort().at(-1);
 await page.goto(base+'/?view=detail');await page.waitForSelector('.trend-point');
 assert.equal(await page.locator('[data-period="5y"]').getAttribute('aria-pressed'),'true');
 assert.equal(await page.locator('#period-start').inputValue(),time.preset('5y',anchor).start);
 assert.ok(!(await page.locator('#metrics').innerText()).includes('+33'));
 assert.ok((await page.locator('.trend-svg').getAttribute('aria-label')).includes('X축'));
 await page.locator('[data-period="1y"]').click();
 assert.equal(await page.locator('#period-start').inputValue(),time.preset('1y',anchor).start);
 assert.equal(await page.locator('#period-unit').inputValue(),'month');
 await page.locator('[data-period="1q"]').click();
 assert.equal(await page.locator('#period-start').inputValue(),time.preset('1q',anchor).start);
 assert.equal(await page.locator('#period-unit').inputValue(),'week');
 await page.locator('[data-tab="context"]').click();await page.locator('[data-tab="observe"]').click();
 await page.waitForFunction(()=>document.querySelector('.trend-svg').viewBox.baseVal.width>600);
 const point=page.locator('.trend-point').first();const bin=await point.getAttribute('data-bin');
 const before=await point.getAttribute('aria-label');const expected=Number(before.match(/· (\d+)건/)[1]);
 await point.click();assert.ok((await page.locator('#paper-count').innerText()).startsWith(`${expected}건`));
 assert.equal(await page.locator(`[data-bin="${bin}"]`).getAttribute('aria-pressed'),'true');
 await page.locator(`[data-bin="${bin}"]`).press('Enter');assert.ok(await page.locator('#clear-year').isHidden());
 await page.locator('#period-start').fill('2024-01-01');await page.locator('#period-end').fill('2024-12-31');await page.locator('#period-unit').selectOption('month');
 await page.locator('#period-form button[type="submit"]').click();
 assert.equal(await page.locator('#metrics strong').first().innerText(),initial.chemicals[0].papers.filter(p=>p.date>='2024-01-01'&&p.date<='2024-12-31').length+'건');
 assert.equal(await page.locator('.trend-point').count(),12);
 await page.locator('[data-chemical="bps"]').click();
 assert.equal(await page.locator('#period-start').inputValue(),'2024-01-01');
 await page.locator('#period-end').fill('2030-10-20');await page.locator('[data-period="1q"]').click();
 assert.equal(await page.locator('.trend-point').count(),0);
 assert.ok((await page.locator('#chart').innerText()).includes('수집 자료가 없습니다'));
 assert.equal(await page.locator('#metrics strong').first().innerText(),'—');
 await page.locator('#period-end').fill(anchor);await page.locator('[data-period="1q"]').click();
 await page.locator('[data-chemical="6ppd-q"]').click();
 assert.ok(await page.locator('.trend-point').count()>0);
 await page.locator('section.panel').filter({has:page.locator('#chart')}).screenshot({path:'.data/pioneer-period-line.png'});
 await page.setViewportSize({width:390,height:844});
 for(const preset of ['5y','1y','1q']){await page.locator(`[data-period="${preset}"]`).click();assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);}
 await page.screenshot({path:'.data/pioneer-period-mobile.png',fullPage:false});
 const latest=await(await page.request.get(base+'/api/research')).json();assert.equal(latest.review_history.length,0);assert.equal(latest.evaluations.length,0);
 assert.deepEqual(errors,[]);console.log(JSON.stringify({passed:['5-year quarterly view','1-year monthly view','quarter weekly view','line graph with time axis','numeric change card removed','point-to-paper count','keyboard toggle','custom dates','period retained across chemicals','uncollected is gap not zero','mobile three presets','no database review writes'],browserErrors:errors}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
