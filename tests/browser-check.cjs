// Run against a marked validation copy; never write automated reviews into the live DB.
const {chromium}=require('playwright');
const timeline=require('../web/timeline.js');
const base=process.env.PIONEER_TEST_URL||'http://127.0.0.1:8767';
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
 const initial=await(await page.request.get(base+'/api/research')).json();
 if(!initial.validation_copy)throw Error('Refusing automated review writes to a DB without validation_copy marker');
 await page.goto(base+'/?view=detail');await page.waitForSelector('.paper');
 const chem=initial.chemicals[0];
 if(!(await page.locator('#mode').innerText()).includes('검증용 복제 DB'))throw Error('validation marker missing');
 const range=timeline.preset('5y',initial.chemicals.map(timeline.coverage).filter(Boolean).map(c=>c.end).sort().at(-1));
 const bin=timeline.series(chem,range).bins.find(b=>b.count>0&&b.covered);
 await page.locator(`[data-bin="${bin.id}"]`).click();
 if(!(await page.locator('#paper-count').innerText()).startsWith(`${bin.count}건`))throw Error('chart/list mismatch');
 await page.locator('#clear-year').click();
 await page.locator('#search').fill('non-matching-zzz');
 if(await page.locator('.paper').count())throw Error('search failed');
 await page.locator('#search').fill('');
 await page.locator('[data-facet="medium"]').selectOption('water');
 const inPeriod=new Set(chem.papers.filter(p=>timeline.inRange(p,range)).map(p=>p.record_key));
 const waterRecords=new Set(chem.evidence.filter(e=>inPeriod.has(e.record_key)&&e.dimension==='medium'&&e.label==='water'&&e.review?.status!=='rejected'&&e.paper_review?.status!=='rejected').map(e=>e.record_key));
 if(!(await page.locator('#paper-count').innerText()).startsWith(`${waterRecords.size}건`))throw Error('facet filter mismatch');
 await page.locator('[data-facet="medium"]').selectOption('');
 await page.locator('[data-tab="context"]').click();
 if(await page.locator('.cell-button').count()!==48)throw Error('matrix shape wrong');
 await page.locator('#level-filter').selectOption('fulltext');
 if(!(await page.locator('.evidence-row').count()))throw Error('fulltext evidence missing');
 await page.locator('#tab-context [data-review-kind="evidence"]').first().click();
 await page.locator('#review-actor').fill('UI 자동검사 (사람 아님)');
 await page.locator('#review-reason').fill('자동화된 저장 동작 검증이며 과학적 평가가 아닙니다.');
 await page.locator('#review-status').selectOption('uncertain');
 await page.locator('#review-form button[type="submit"]').click();
 await page.waitForFunction(()=>!document.getElementById('review-dialog').open,{timeout:30000});
 const updated=await(await page.request.get(base+'/api/research')).json();
 if(updated.review_history.length!==initial.review_history.length+1)throw Error('review not persisted');
 await page.locator('[data-tab="questions"]').click();
 if(!(await page.locator('.question').count()))throw Error('questions missing');
 if(!(await page.locator('#tab-questions').innerText()).includes('확정된 연구공백'))throw Error('gap uncertainty missing');
 await page.locator('[data-tab="compare"]').click();
 await page.locator('#compare-select').selectOption('6ppd');
 await page.waitForSelector('.relation-graphic',{timeout:30000});
 if(!(await page.locator('#compare-result').innerText()).includes(Array.from({length:Math.min(chem.run.end_year,new Date().getFullYear()-1)-Math.max(chem.run.start_year,initial.chemicals.find(c=>c.id==='6ppd').run.start_year)+1},(_,i)=>Math.max(chem.run.start_year,initial.chemicals.find(c=>c.id==='6ppd').run.start_year)+i).join(', ')))throw Error('common-year restriction missing');
 await page.locator('[data-comparison-side="a"]').first().click();
 if(!(await page.locator('#comparison-papers').innerText()).includes('비교 건수에 포함된'))throw Error('comparison drilldown missing');
 await page.locator('.manual-relation>summary').click();
 const reference=chem.papers.find(p=>p.year===2024);
 await page.locator('#relation-record').selectOption(reference.record_key);
 await page.locator('#relation-type').selectOption('hypothesis');
 await page.locator('#relation-field').fill('title');
 await page.locator('#relation-quote').fill(reference.title);
 await page.locator('#relation-actor').fill('UI 자동검사 (사람 아님)');
 await page.locator('#relation-reason').fill('저장 문장 일치 검증용이며 실제 과학적 관계 제안이 아닙니다.');
 await page.locator('#relation-form button').click();
 await page.waitForFunction(()=>document.getElementById('action-message').textContent.startsWith('완료'));

 await page.locator('[data-tab="candidates"]').click();
 if(!(await page.locator('.candidate').count()))throw Error('candidate inbox missing');
 await page.locator('[data-tab="audit"]').click();
 if(await page.locator('.method').count()!==3)throw Error('method provenance missing');
 await page.locator('#evaluation-panel>details>summary').click();
 await page.locator('#evaluation-participant').fill('UI 자동검사 (실제 참여자 아님)');
 await page.locator('#evaluation-task').fill('과업 기록 기능 검증·실제 효용 평가 아님');
 await page.locator('#evaluation-start button').click();
 await page.waitForFunction(()=>document.getElementById('action-message').textContent.startsWith('완료'));
 await page.locator('.evaluation>summary').last().click();
 const form=page.locator('.evaluation-finish').last();
 await form.locator('[name="checked"]').fill('0');
 await form.locator('[name="correct"]').fill('0');
 await form.locator('[name="usefulness"]').fill('1');
 await form.locator('[name="evaluator"]').fill('UI 자동검사');
 await form.locator('[name="notes"]').fill('복제 DB의 기능 검사입니다. 실제 사람 평가가 아니며 성과로 보고하지 않습니다.');
 await form.locator('button').click();
 await page.waitForFunction(()=>document.getElementById('action-message').textContent.startsWith('완료'));
 if(!(await page.locator('.evaluation-results').innerText()).includes('N/A'))throw Error('zero-denominator evaluation wrong');

 await page.locator('#minimum-count').fill('9999');
 const sensitivity=page.waitForResponse(r=>r.url().includes('/api/research?'));
 await page.locator('#signal-form button').click();await sensitivity;
 await page.waitForFunction(()=>document.querySelector('.sensitivity')?.innerText.includes('건수≥9999'));
 if(await page.locator('#minimum-count').inputValue()!=='9999')throw Error('threshold input/result mismatch');
 await page.locator('[data-tab="context"]').click();
 await page.locator('#reset-evidence').click();
 await page.screenshot({path:'.data/pioneer-context.png',fullPage:false});
 await page.setViewportSize({width:390,height:844});
 for(const tab of ['observe','context','questions','compare','candidates','audit']){
  await page.locator(`[data-tab="${tab}"]`).click();
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('mobile overflow '+tab);
 }
 await page.locator('[data-tab="context"]').click();
 await page.screenshot({path:'.data/pioneer-mobile.png',fullPage:false});
 const exportData=await(await page.request.get(base+'/api/export')).json();
 if(exportData.chemicals[0].papers.length!==chem.papers.length)throw Error('export raw snapshot mismatch');
 const csv=await(await page.request.get(base+'/api/export.csv')).text();
 if(!csv.includes('source_id')||!csv.includes('chemical_id'))throw Error('CSV export failed');
 const blocked=await page.request.post(base+'/api/review',{headers:{Origin:'https://evil.example'},data:{}});
 if(blocked.status()!==403)throw Error('cross-origin write accepted');
 if(errors.length)throw Error(errors.join('\n'));
 console.log(JSON.stringify({passed:['validation-copy isolation','facet filter','comparison record drilldown','manual relation provenance','task evaluation recording','chart evidence count','text filter','48-cell matrix','licensed fulltext extraction','review persistence','gap uncertainty','common-period comparison','relation provenance','candidate inbox','method sources','threshold sensitivity','mobile all six tabs','JSON and CSV export','cross-origin rejection'],browserErrors:errors,papers:chem.papers.length}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
